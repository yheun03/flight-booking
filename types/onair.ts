export type AirportCode = 'ICN' | 'NRT' | 'BKK' | 'CDG';
export type SegmentId = 'outbound' | 'inbound';
export type FareId = 'light' | 'standard' | 'flex';
export type MealId = 'regular' | 'vegetarian' | 'fruit';
export type Search = { trip: 'oneway' | 'roundtrip'; from: AirportCode; to: AirportCode; departure: string; returning: string; adults: number };
export type Passenger = { id: string; firstName: string; lastName: string; birth: string };
export type Flight = {
    id: string;
    segment: SegmentId;
    number: string;
    from: AirportCode;
    to: AirportCode;
    date: string;
    departure: string;
    arrival: string;
    arrivalDate: string;
    duration: number;
    aircraft: 'A321' | 'B787-9';
    fare: FareId;
    price: number;
    tax: number;
    miles: number;
    earnedMiles: number;
    departureUtc: number;
};
export type PassengerService = { seat: string; meal: MealId | ''; checkedIn: boolean };
export type Booking = {
    id: string;
    transactionId: string;
    createdAt: string;
    flights: Flight[];
    passengers: Passenger[];
    contact: { email: string; phone: string };
    method: 'card' | 'miles';
    fare: number;
    tax: number;
    miles: number;
    services: Record<string, Record<string, PassengerService>>;
};
